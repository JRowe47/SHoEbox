"""Verify the completed checkpoint and export compact, reproducible deliverables."""
import argparse
import csv
import hashlib
import json
import math
import os
from pathlib import Path
import shutil
import sys
import zipfile

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from shoe_multiscale import Model
from experiments.scale_100m.train import frozen_score, file_hash


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--run', type=Path, required=True)
    p.add_argument('--data', type=Path, required=True)
    p.add_argument('--evidence', type=Path, required=True)
    p.add_argument('--out', type=Path, required=True)
    a = p.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    r = json.loads((a.run/'results.json').read_text())
    manifest = json.loads((a.data/'manifest.json').read_text())
    assert r['checkpoint_targets'] == 20_000_000 and r['completed_utc']
    checkpoint = a.run/'latest.shoe'
    assert file_hash(checkpoint) == r['checkpoint_sha256']
    final = r['metrics'][-1]
    final_nll = final['development_nll']
    dev = np.memmap(a.data/'development.bin', mode='r', dtype=np.uint8)
    docs = manifest['files']['development']['documents']

    with Model.load(checkpoint) as m:
        assert m.parameter_count == 100_009_791
        assert int(m.routing_stats()['levels'][0]['events']) == 20_000_000
        assert m.stats()['routing_arm'] == 'D'
        repeated_nll, _ = frozen_score(m, dev, docs)
        assert repeated_nll == final_nll
        before = hashlib.sha256(m.dumps()).hexdigest()
        assert before == r['checkpoint_sha256']
        with m.clone() as uninterrupted:
            continuation = dev[:2050]
            loss1 = uninterrupted.run(continuation[:-1], continuation[1:])
            loss2 = m.run(continuation[:-1], continuation[1:])
            assert loss1 == loss2
            assert hashlib.sha256(uninterrupted.dumps()).digest() == hashlib.sha256(m.dumps()).digest()
    verification = dict(exact_training_targets=20_000_000, actual_parameters=100_009_791,
        checkpoint_sha256=r['checkpoint_sha256'], reloaded_development_nll=repeated_nll,
        exact_evaluation_reproduction=True, evaluation_preserved_checkpoint=True,
        continuation_targets=2049, exact_continuation_loss=True, exact_continuation_state=True)
    (a.out/'SHoEbox_100M_FineWeb_20M_Verification.json').write_text(json.dumps(verification, indent=2))
    with Model.load(checkpoint) as m:
        m.finish()
        samples = []
        for prompt in ('The purpose of this article is ', 'In a small town in the mountains, ', 'The computer network uses '):
            samples.append(dict(prompt=prompt, temperature=.8, seed=7,
                text=m.generate(prompt, length=512, temperature=.8, seed=7, clear_memory=True).decode('utf-8', 'replace')))
    (a.out/'SHoEbox_100M_FineWeb_20M_Samples.txt').write_text('\n\n'.join(
        f"Prompt: {s['prompt']}\nTemperature: 0.8 | Seed: 7 | 512 generated bytes\n\n{s['text']}" for s in samples))
    curve_file = a.out/'SHoEbox_100M_FineWeb_20M_Curves.csv'
    with curve_file.open('w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=['training_bytes', 'training_seconds', 'wall_seconds',
            'online_train_nats_per_byte', 'held_out_nats_per_byte', 'held_out_bits_per_byte'])
        w.writeheader()
        for row in r['metrics']:
            w.writerow(dict(training_bytes=row['targets'], training_seconds=row['train_seconds'],
                wall_seconds=row['wall_seconds'], online_train_nats_per_byte=row['train_nll'],
                held_out_nats_per_byte=row['development_nll'],
                held_out_bits_per_byte=row['development_nll']/math.log(2) if row['development_nll'] is not None else None))

    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    plt.rcParams.update({'font.family': 'DejaVu Sans', 'font.size': 11,
        'axes.spines.top': False, 'axes.spines.right': False, 'axes.labelcolor': '#334155',
        'text.color': '#0f172a', 'xtick.color': '#475569', 'ytick.color': '#475569'})
    fig, (ax, at) = plt.subplots(1, 2, figsize=(13.8, 5.5), gridspec_kw={'width_ratios': [1.4, 1]})
    train = [q for q in r['metrics'] if q['train_nll'] is not None]
    valid = [q for q in r['metrics'] if q['targets'] > 0 and q['development_nll'] is not None]
    ax.plot([q['targets']/1e6 for q in train], [q['train_nll'] for q in train],
        color='#e69b36', lw=1.5, alpha=.85, label='Online training · 250K-byte windows')
    ax.plot([q['targets']/1e6 for q in valid], [q['development_nll'] for q in valid],
        color='#176d91', lw=2.6, marker='o', ms=4, label='Frozen validation · same 262,144 bytes')
    ax.set(xlabel='FineWeb training bytes (millions)', ylabel='Loss (nats per byte)', xlim=(0, 20.5))
    ax.legend(frameon=False, fontsize=9, loc='upper right')
    at.plot([q['train_seconds']/60 for q in valid], [q['development_nll'] for q in valid],
        color='#176d91', lw=2.6, marker='o', ms=4)
    at.set(xlabel='Measured training time (minutes)', ylabel='Held-out loss (nats per byte)')
    at.text(.97, .95, f"Final validation\n{final_nll:.4f} nats/byte\n{final_nll/math.log(2):.4f} bits/byte",
        transform=at.transAxes, ha='right', va='top', fontsize=13, fontweight='bold', color='#176d91')
    for axis in (ax, at):
        axis.grid(axis='y', color='#e2e8f0', lw=.7)
        axis.set_axisbelow(True)
    fig.suptitle('SHoEbox 100M · 20M FineWeb training bytes', x=.065, ha='left', fontsize=19, fontweight='bold')
    fig.text(.065, .895, 'Routing D  |  width 64  |  four scales  |  100,009,791 fitted parameters', fontsize=11, color='#475569')
    fig.text(.065, .025, f"Fresh-model validation: {r['metrics'][0]['development_nll']:.4f} nats/byte (not plotted).  "
        f"Training: {r['training_bytes_per_second']:,.0f} bytes/s.  Validation and checkpoint time excluded from training time.",
        fontsize=9, color='#475569')
    fig.subplots_adjust(left=.065, right=.98, top=.83, bottom=.17, wspace=.3)
    fig.savefig(a.out/'SHoEbox_100M_FineWeb_20M_Loss.png', dpi=180, facecolor='white')
    plt.close(fig)

    milestones = [q for q in valid if q['targets'] in {1_000_000, 4_000_000, 8_000_000, 12_000_000, 16_000_000, 20_000_000}]
    table = '\n'.join(f"| {q['targets']/1e6:.0f}M | {q['development_nll']:.6f} | {q['development_nll']/math.log(2):.6f} | {q['train_seconds']/60:.2f} |" for q in milestones)
    bank_rows = '\n'.join(f"| {name} | {span} | {count:,} | {int(level['minimum_selections']):,}–{int(level['maximum_selections']):,} |"
        for name, span, count, level in zip(['Fast', 'L1', 'L2', 'L3'], [1, 4, 16, 64], r['experts'], r['final_routing']['levels']))
    report = f"""# SHoEbox 100M — 20M FineWeb-byte training run

Created a fresh **100,009,791-parameter routing D model** and completed exactly **20,000,000 next-byte training targets**. Final held-out loss is **{final_nll:.6f} nats/byte** ({final_nll/math.log(2):.6f} bits/byte). Training took **{r['train_seconds']/60:.2f} minutes**, averaging **{r['training_bytes_per_second']:,.0f} bytes/s**; total run time including evaluation and checkpoint writes was **{r['wall_seconds']/60:.2f} minutes**.

## Model

Based on main commit `{r['source_commit']}` (selected routing D). Width stays 64, with one active expert per event and four ordered children per slow event. Capacity is increased through expert banks. Retained recall, addressed recurrent memory, separate learning rates, constituent credit, centered normalized exact routing, fading utilization warmup, and predictive SDR objectives remain enabled. The experimental additional routing depth is not included.

| Scale | Bytes/event | Experts | Final selections/expert: min–max |
|---|---:|---:|---:|
{bank_rows}

The nominal budget is 100M; three predictor heads and whole-expert rounding produce the fitted total above. Checkpoint format remains version 9.

## Training data and schedule

- FineWeb `HuggingFaceFW/fineweb`, `sample-10BT`, official row API; exact source-text and binary hashes recorded in the included manifest.
- **{r['train_documents']:,} training documents**, **{r['development_documents']} disjoint development documents**, **{r['development_targets']:,} fixed validation targets**. Validation IDs and complete-text hashes are excluded from training. Training targets are visited once, without corpus repetition.
- UTF-8 text plus two newline bytes per document. The training binary contains **{manifest['files']['train']['bytes']:,} bytes**: 20M prediction targets plus one initial context byte per document. The final document is truncated to the exact target budget.
- Seed **7**; document-aware 4,096-target chunks, shuffled once. Context and memory reset at chunk boundaries; next-byte pairs never cross documents.
- Peak fast/query rate **0.008**, slow **0.08**, head **0.16**. Linear warmup over **200K targets**, then cosine decay to **10%** of those rates across the full 20M targets. Prototype attraction **0.002**, contrastive weight **0.1**, reconstruction weight **0.05**, full constituent credit.
- The schedule is stretched over this 20M run; it does not apply the earlier 1M-model experiment's extra rate reduction after 5M.

## Measured learning

| Training targets | Held-out nats/byte | Held-out bits/byte | Training minutes |
|---:|---:|---:|---:|
{table}

Fresh-model held-out loss was {r['metrics'][0]['development_nll']:.6f} nats/byte. Online training loss in the chart averages each 250K-target window, while held-out loss always evaluates the same development documents. Evaluation finishes pending credit on a clone, freezes learning, and clears context per validation document. It does not modify the resumable checkpoint.

## Runtime changes and verification

Raised the constructor's nominal budget limit from 6M to 100M. Large exact-search banks use a derived prototype cache tiled across 16 experts, with AVX-512/AVX2 and portable paths. All experts are scored with the original per-dot float operation order and tie-breaking. Learning rules and serialized state are unchanged; cached copies are rebuilt after loading.

The optimized and cap-only D runtimes produced identical loss and checkpoint bytes in 12M-parameter/90K-target and 100M-parameter/4,096-target comparisons, including seeded routing, frozen evaluation and cross-runtime continuation. The measured 100M routing smoke test improved by approximately 5.8× under that check. The full regression suite passed: 2,093 native checks, 25 Python tests, 19 semantic-lace checks and 26 routing checks. Additional direct tiled-arithmetic checks expanded the routing suite to 44 passing checks. ASan and UBSan passed with LSan explicitly disabled on the managed host.

The final saved checkpoint was reloaded and independently reevaluated, reproducing {repeated_nll:.6f} exactly. Its persistent fast-routing counter verifies 20M training targets. An additional 2,049-target continuation on disposable copies matched exactly in loss and serialized state; those verification targets were not added to the delivered checkpoint.

## Files and use

- `SHoEbox_100M_FineWeb_20M.shoe`: one resumable checkpoint, **{r['checkpoint_bytes']/1024**2:.1f} MiB**, preserving unfinished local credit and stream state.
- `SHoEbox_100M_FineWeb_20M_Runtime_and_Results.zip`: compatible source, training scripts, data manifest, results, checks and this report. It excludes trained weights and the full training dataset.
- `SHoEbox_100M_FineWeb_20M_Loss.png`, `SHoEbox_100M_FineWeb_20M_Curves.csv`, and `SHoEbox_100M_FineWeb_20M_Samples.txt`.

Extract the runtime bundle and run with its `runtime` directory on `PYTHONPATH`. Requirements are Python, NumPy, and a C++17 compiler. The unmodified earlier main release rejects the 100M budget when loading, so use the included compatible runtime.

```python
from shoe_multiscale import Model
with Model.load('SHoEbox_100M_FineWeb_20M.shoe') as model:
    model.finish()  # include pending local updates before frozen generation
    print(model.generate('The purpose of this article is ',
                         length=512, temperature=0.8,
                         seed=7, clear_memory=True).decode('utf-8', 'replace'))
```

The included runner resumes the saved chunk order and rate schedule using `--resume`, `results.json`, `latest.shoe`, and the exact data manifest. For additional new documents, explicitly choose the next training schedule and reset context at document/chunk boundaries.

Checkpoint SHA-256: `{r['checkpoint_sha256']}`.
"""
    (a.out/'SHoEbox_100M_FineWeb_20M_Report.md').write_text(report)
    target = a.out/'SHoEbox_100M_FineWeb_20M.shoe'
    if target.exists(): target.unlink()
    os.link(checkpoint, target)
    shutil.copy2(a.run/'results.json', a.out/'SHoEbox_100M_FineWeb_20M_Results.json')
    bundle = a.out/'SHoEbox_100M_FineWeb_20M_Runtime_and_Results.zip'
    with zipfile.ZipFile(bundle, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        z.writestr('runtime/SOURCE_COMMIT.txt', r['source_commit']+'\n')
        z.write(ROOT/'shoe_multiscale.py', 'runtime/shoe_multiscale.py')
        z.write(ROOT/'AGENTS.md', 'runtime/AGENTS.md')
        for folder in (ROOT/'multiscale', ROOT/'experiments/scale_100m'):
            for f in sorted(folder.rglob('*')):
                if f.is_file() and '__pycache__' not in f.parts and f.suffix in {'.py', '.cpp', '.hpp', '.md', '.json'}:
                    z.write(f, 'runtime/'+str(f.relative_to(ROOT)))
        for f in sorted(a.out.iterdir()):
            if f.suffix not in {'.shoe', '.zip'}:
                z.write(f, f.name)
        z.write(a.data/'manifest.json', 'data/manifest.json')
        z.write(a.data/'development.bin', 'data/development.bin')
        z.write(a.run/'development_per_document.json', 'evidence/development_per_document.json')
        for name in ('exact_parity.json', 'regression_tests.log'):
            z.write(a.evidence/name, 'evidence/'+name)
        z.writestr('README.md', '''# SHoEbox 100M FineWeb run

The trained checkpoint is delivered separately as SHoEbox_100M_FineWeb_20M.shoe.
Use the included runtime: the earlier unmodified main cannot load a 100M model.

## Load and generate

Install NumPy and a C++17 compiler, then set PYTHONPATH to the runtime directory.
See the report's Python example. First use builds a local CPU shared library.

## Reproduce the data and run

From the extracted bundle directory:

```bash
python runtime/experiments/scale_100m/prepare.py --previous-data data --out prepared_data --cache row_cache
python runtime/experiments/scale_100m/train.py --data prepared_data --out reproduced_run
```

The preparer downloads official FineWeb rows and rejects a changed source sample
whose training binary differs from the pinned SHA-256. The included development
split is preserved and excluded from training. The full 20M training binary and
intermediate trained models are not duplicated in this package.

To recover an interrupted reproduction, add --resume and retain its results.json,
latest.shoe and exact prepared_data. The completed delivered run's metadata is
SHoEbox_100M_FineWeb_20M_Results.json.
''')
    print(json.dumps(dict(completed=True, final_nll=final_nll, checkpoint=str(target),
        files=[dict(name=f.name, bytes=f.stat().st_size) for f in a.out.iterdir() if f.is_file()])), flush=True)


if __name__ == '__main__':
    main()
