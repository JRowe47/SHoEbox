class GraphPublicationChecks(unittest.TestCase):
    def config(self, **kwargs):
        values = dict(task_publication=('A','B','C','U','V'), publication_payload_rank=4,
            publication_state_commit='publication', recall_slots=2, rounds=2, recurrent_feedback=True, seed=19)
        values.update(kwargs)
        return GraphConfig.tiny(**values)

    def model(self, **kwargs):
        torch.manual_seed(19)
        return RegionLanguageModel(self.config(**kwargs))

    def same(self, a, b):
        left, right = tensor_list(a), tensor_list(b)
        self.assertEqual(len(left), len(right))
        for x, y in zip(left, right):
            torch.testing.assert_close(x, y, atol=0, rtol=0)

    def test_legacy_initialization_rng_and_forced_write_equivalence(self):
        torch.manual_seed(19)
        legacy = RegionLanguageModel(self.config(task_publication=(), publication_payload_rank=0))
        rng = torch.get_rng_state()
        new = self.model(publication_state_commit='always')
        self.same(rng, torch.get_rng_state())
        for n, value in legacy.state_dict().items():
            self.same(value, new.state_dict()[n])
        x = torch.tensor([[2,3,4],[7,8,9]])
        self.same(legacy(x)['logits'], new(x, publication_overrides={n:'always' for n in new.cfg.task_publication})['logits'])

    def test_true_holds_keep_payload_header_contents_and_version(self):
        model = self.model()
        before = model(torch.tensor([[2],[3]]))['state'].detach()
        after = model(torch.tensor([[4],[5]]), state=before,
            publication_overrides={n:'hold' for n in model.cfg.task_publication}, return_write_activity=True)
        for name in model.cfg.task_publication:
            self.same(before.ports.latest[name], after['state'].ports.latest[name])
            self.same(before.nodes[name].contextualizer, after['state'].nodes[name].contextualizer)
            self.same(before.nodes[name].blocks, after['state'].nodes[name].blocks)
            self.same(after['state'].nodes[name].clock, before.nodes[name].clock+2)
        self.assertFalse(after['write_activity']['write_eligible'].any())

    def test_bootstrap_inactive_rows_reset_and_state_serialization(self):
        model = self.model()
        masks = {n: torch.tensor([[True,True],[False,True]]) for n in model.nodes}
        reset = torch.tensor([[False,True],[False,False]])
        result = model(torch.tensor([[2,3],[4,5]]), reset=reset, node_masks=masks, return_write_activity=True)
        a = result['write_activity']
        self.assertEqual(a['write_probs'].shape, (2,4,5))
        self.assertFalse(a['write_active'][1,:2].any())
        self.assertFalse(a['write_eligible'][0,0].any())
        self.assertFalse(a['write_eligible'][0,2].any())
        self.assertTrue(a['write_actions'][0,0].eq(1).all())
        self.same(a['reset'], torch.tensor([[False,False,True,False],[False,False,False,False]]))
        credit = make_graph_eligibility(model,2).advance(a)
        credit.capture(result['state'])
        self.same(result['state'], GraphState.from_dict(result['state'].to_dict()))
        cleared = result['state'].reset(torch.tensor([True,False]))
        self.assertTrue(all(not d[0].any() for d in cleared.publication_demand.values()))
        self.assertTrue(all(not p.version[0] for p in cleared.ports.latest.values()))

    def test_demand_is_previous_round_usage_and_blocked_reads_zero_it(self):
        model = self.model()
        x = torch.tensor([[2,3],[4,5]])
        first = model(x[:,:1], return_write_activity=True)
        a = first['write_activity']['demand']
        self.assertFalse(a[:,0].any())
        self.assertGreater(float(a[:,1].sum()),0.)
        second = model(x[:,1:], state=first['state'], return_write_activity=True)
        self.same(second['write_activity']['demand'][:,0],
                  torch.stack([first['state'].publication_demand[n] for n in model.cfg.task_publication],1))
        blocked = model(x, recall_control='blocked', return_write_activity=True)
        self.assertFalse(blocked['write_activity']['demand'].any())
        # Same-round writers never see demand generated by later-stage readers.
        with torch.no_grad():
            model.publisher.demand_features.weight.fill_(.2)
        together = model(x, return_write_activity=True)
        reverse = model(x, reverse_independent=True, return_write_activity=True)
        self.same(together['logits'], reverse['logits'])
        self.same(together['write_activity'], reverse['write_activity'])

    def test_cross_round_demand_has_live_task_gradient(self):
        model = self.model()
        with torch.no_grad():
            model.publisher.demand_features.weight.fill_(.1)
        result = model(torch.tensor([[2,3,4],[4,5,6]]), return_write_activity=True)
        result['logits'].square().mean().backward()
        for parameter in (model.publisher.policy, model.publisher.memory_features.weight,
                          model.publisher.demand_features.weight, model.publisher.payload_adapter.coefficients):
            self.assertIsNotNone(parameter.grad)
            self.assertTrue(torch.isfinite(parameter.grad).all())
            self.assertGreater(float(parameter.grad.norm()),0.)

    def test_credit_rejects_stale_versions_epochs_and_owner_order(self):
        model = self.model()
        state = model.initial_state(2)
        credit = make_graph_eligibility(model,2)
        with self.assertRaisesRegex(ValueError,'version/epoch'):
            credit.capture(replace(state, epochs=state.epochs+1))
        with self.assertRaisesRegex(ValueError,'version/epoch'):
            credit.capture(model(torch.tensor([[2],[3]]))['state'])
        saved = credit.to_dict()
        saved['trace']['write']['owners'] = tuple(reversed(model.cfg.task_publication))
        with self.assertRaisesRegex(ValueError,'owner'):
            make_graph_eligibility(model,2,saved)

    def test_conditional_gate_and_payload_gradients_match_across_boundary(self):
        # Frozen candidates isolate exactly the estimator's advertised derivative.
        model = self.model(task_publication=('A',), rounds=1)
        with torch.no_grad():
            model.publisher.policy.zero_(); model.publisher.policy[:,-1].fill_(-.6)
        weights = deepcopy(model.state_dict())
        answers = []
        for detached in (False, True):
            model.load_state_dict(weights); model.zero_grad(set_to_none=True)
            state = model.initial_state(1)
            credit = make_graph_eligibility(model,1)
            credit = replace(credit, trace=replace(credit.trace, write=replace(credit.write, decay=1.)))
            boundary = None
            for index in range(4):
                if index == 2 and detached:
                    state, boundary = credit.capture(state.detach())
                old = state.ports.latest['A']
                latent = torch.linspace(-1,1,model.cfg.width)[None] + index*.2
                result = dict(latent=latent, header=old.header, state=state.nodes['A'], previous_state=state.nodes['A'])
                pub, node, activity = model.publisher('A',old,result,torch.tensor([True]),
                    state.epochs, state.events_seen, torch.tensor([0]), (), state.publication_demand['A'],model.cfg)
                state = replace(state, ports=TensorPorts({**state.ports.latest,'A':pub}), events_seen=state.events_seen+1)
                activity = {k:v[:,None,None] for k,v in activity.items()}
                activity['reset'] = torch.zeros(1,1,dtype=torch.bool)
                credit = credit.advance(activity)
            state.memory_tensor(('A',)).square().sum().backward()
            if boundary is not None:
                boundary.apply(model.publisher.policy)
                boundary.apply_payload(model.publisher.payload_adapter)
                with self.assertRaises(RuntimeError):
                    boundary.apply(model.publisher.policy)
                with self.assertRaises(RuntimeError):
                    boundary.apply_payload(model.publisher.payload_adapter)
            answers.append((model.publisher.policy.grad.clone(),model.publisher.payload_adapter.coefficients.grad.clone()))
        for a,b in zip(*answers):
            torch.testing.assert_close(a,b,rtol=1e-5,atol=1e-6)

    def test_chunked_graph_is_identical_and_no_recall_mode_works(self):
        for slots in (0,2):
            model = self.model(recall_slots=slots, recurrent_feedback=bool(slots))
            x = torch.tensor([[1,2,3],[5,6,7]])
            complete = model(x)
            a = model(x[:,:1]); b = model(x[:,1:],state=a['state'].detach())
            self.same(complete['logits'], torch.cat((a['logits'],b['logits']),1))
            self.same(complete['state'], b['state'])

    def run_model(self, enabled=True):
        return GraphMixedRun(b'A small language stream.\n'*150, self.config(rounds=1),
            TaskStreamConfig(delays=(0,2),cycles=1,acquisition_queries=True),
            dict(seed=19,data_seed=283,batch=2,context=8,documents=8,lr=.002,
                 syntax_weight=.1,truncate_every=4,eval_chunks=1,eval_count=2,delayed_credit=enabled))

    def test_exact_resume_includes_demand_credit_optimizer_and_both_cursors(self):
        run = self.run_model()
        for _ in range(3):
            run.advance()
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory)/'last.pt'; run.save(path)
            for _ in range(3):
                run.advance()
            resumed = self.run_model(); resumed.restore(path)
            for _ in range(3):
                resumed.advance()
        self.same(run.model.state_dict(),resumed.model.state_dict())
        self.same(run.optimizer.state_dict(),resumed.optimizer.state_dict())
        for key in run.states:
            self.same(run.states[key],resumed.states[key])
            self.same(run.credits[key].to_dict(),resumed.credits[key].to_dict())
            self.assertEqual(run.streams[key].state_dict(),resumed.streams[key].state_dict())
        self.assertEqual(run.totals,resumed.totals)

    def test_source_isolation_and_no_credit_arm_same_first_forward(self):
        run, control = self.run_model(), self.run_model(False)
        untouched = deepcopy(run.states['memory'])
        first, other = run.advance(),control.advance()
        self.assertEqual(first['primary_nll'],other['primary_nll'])
        self.same(run.states['memory'],untouched)
        for _ in range(3):
            run.advance(); control.advance()
        self.assertGreater(run.totals['language']['delayed_gradient_norm_sum'],0.)
        self.assertEqual(control.totals['language']['delayed_gradient_norm_sum'],0.)
        self.assertEqual(control.totals['language']['payload_gradient_norm_sum'],0.)

    def test_graph_evaluation_and_controls_leave_configuration_intact(self):
        run = self.run_model()
        metrics,traces = run.memory_metrics()
        self.assertGreater(metrics['answers'],0)
        self.assertEqual(metrics['answers'],len(traces))
        self.assertEqual(set(metrics['owners']),set(run.model.cfg.task_publication))
        original = run.model.cfg
        with self.assertRaises(RuntimeError):
            with intervention(run.model,'no_feedback'):
                self.assertFalse(run.model.connections.cfg.recall_feedback)
                self.assertFalse(run.model.cfg.publication_feedback)
                raise RuntimeError('restore')
        self.assertIs(original,run.model.cfg)
        self.assertIs(original,run.model.connections.cfg)

    def test_config_roundtrip_and_invalid_combinations(self):
        cfg = self.config()
        self.assertEqual(cfg,GraphConfig.from_dict(cfg.to_dict()))
        for values in (dict(task_publication=('missing',)),dict(selective_publication=('A',)),
                       dict(publication_features=0),dict(publication_payload_rank=33)):
            with self.assertRaises(ValueError):
                self.config(**values).validate()

    def test_gate_credit_without_payload_adapter(self):
        model = self.model(publication_payload_rank=0)
        credit = make_graph_eligibility(model,1)
        state,boundary = credit.capture(model.initial_state(1))
        result = model(torch.tensor([[2,3]]),state=state,return_write_activity=True)
        self.assertNotIn('payload_features',result['write_activity'])
        credit = credit.advance(result['write_activity'])
        restored = make_graph_eligibility(model,1,credit.to_dict())
        self.same(credit.to_dict(),restored.to_dict())
        restored.capture(result['state'])
        result['logits'].square().mean().backward()
        self.assertEqual(boundary.apply(model.publisher.policy),0.)

    def test_evaluation_cache_reuses_identical_weights_and_recovers_measurements(self):
        run = self.run_model()
        run.language_metrics = Mock(return_value=dict(nll=2.))
        run.memory_metrics = Mock(return_value=(dict(answer_nll=1.),[dict(example=True)]))
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory)
            run.save(path/'best.pt'); run.save(path/'last.pt')
            result = final_evaluation(run,path)
            self.assertEqual(run.language_metrics.call_count,7)
            self.assertEqual(run.memory_metrics.call_count,8)
            self.assertEqual(result['best']['signature'],result['last']['signature'])
            self.assertEqual((path/'best_test_traces.jsonl').read_bytes(),(path/'last_test_traces.jsonl').read_bytes())
            run.language_metrics.reset_mock(); run.memory_metrics.reset_mock()
            final_evaluation(run,path)
            run.language_metrics.assert_not_called(); run.memory_metrics.assert_not_called()
            # A single interrupted/missing measurement requires only that control.
            import json
            cache_path=path/'evaluation_cache.json'; cache=json.loads(cache_path.read_text())
            del cache[result['best']['signature']]['interventions']['blocked']
            cache_path.write_text(json.dumps(cache))
            final_evaluation(run,path)
            self.assertEqual(run.language_metrics.call_count,1)
            self.assertEqual(run.memory_metrics.call_count,1)
            run.protocol['data_seed'] += 1
            final_evaluation(run,path)
            self.assertEqual(run.language_metrics.call_count,8)
            self.assertEqual(run.memory_metrics.call_count,9)


